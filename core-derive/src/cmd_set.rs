//! `#[derive(CmdSet)]`: see the example on `crate::derive_cmd_set`.

/// One variant, after reading and checking its source: its name, the `#[derive(Command)]` args
/// struct it wraps, and its opcode (the variant's own discriminant, e.g. `Name(Args) = 1`).
struct Variant<'a> {
    name: &'a syn::Ident,
    ty: &'a syn::Type,
    opcode: &'a syn::Expr,
}

pub fn expand(input: &syn::DeriveInput) -> syn::Result<proc_macro2::TokenStream> {
    let syn::Data::Enum(data) = &input.data else {
        return Err(syn::Error::new_spanned(
            &input.ident,
            "CmdSet can only be derived for an enum",
        ));
    };
    if !input.generics.params.is_empty() {
        return Err(syn::Error::new_spanned(
            &input.generics,
            "CmdSet does not support generics",
        ));
    }
    check_repr_u16(input)?;

    let variants = data
        .variants
        .iter()
        .map(parse_variant)
        .collect::<syn::Result<Vec<_>>>()?;

    let decode_arms = variants.iter().map(|variant| {
        let name = variant.name;
        let ty = variant.ty;
        let opcode = variant.opcode;
        quote::quote! {
            #opcode => ::core::result::Result::Ok(
                Self::#name(#ty::decode(raw.args.as_slice())?)
            ),
        }
    });
    let opcode_arms = variants.iter().map(|variant| {
        let name = variant.name;
        let opcode = variant.opcode;
        quote::quote! { Self::#name(_) => #opcode, }
    });
    let validate_arms = variants.iter().map(|variant| {
        let name = variant.name;
        quote::quote! { Self::#name(value) => value.validate(), }
    });

    let enum_name = &input.ident;
    Ok(quote::quote! {
        impl #enum_name {
            /// Matches `raw.opcode` against each variant's own opcode (its discriminant) and
            /// decodes that variant's args, or `UnknownOpcode` if none matches. This is "the
            /// router decodes... once", in `docs/design.md`'s "Command Routing": a target's
            /// `CommandTarget::accept` calls this before anything is queued.
            pub fn decode(
                raw: &::vee_core_api::cmd::RawCmd,
            ) -> ::core::result::Result<Self, ::vee_core_api::cmd::CmdErr> {
                match raw.opcode {
                    #(#decode_arms)*
                    _ => ::core::result::Result::Err(::vee_core_api::cmd::CmdErr::UnknownOpcode),
                }
            }

            /// This command's opcode: the variant's own discriminant, the same value `decode`
            /// matches. A sender uses it to fill in `RawCmd::opcode`, so the number is written
            /// only once, on the variant.
            pub fn opcode(&self) -> u16 {
                match self {
                    #(#opcode_arms)*
                }
            }

            /// Delegates to the decoded variant's own `validate` (generated by `#[derive(Command)]`,
            /// or hand-written if that struct has `#[validate]`).
            pub fn validate(&self) -> ::core::result::Result<(), ::vee_core_api::cmd::CmdErr> {
                match self {
                    #(#validate_arms)*
                }
            }
        }
    })
}

/// A variant's opcode is its own discriminant, so Rust requires the enum to say what integer
/// type that is: the same requirement, for the same reason, as `#[derive(Code)]`'s events.
fn check_repr_u16(input: &syn::DeriveInput) -> syn::Result<()> {
    let has_repr_u16 = input.attrs.iter().any(|attr| {
        attr.path().is_ident("repr")
            && attr
                .parse_args::<syn::Ident>()
                .is_ok_and(|repr| repr == "u16")
    });
    if has_repr_u16 {
        Ok(())
    } else {
        Err(syn::Error::new_spanned(
            &input.ident,
            "add `#[repr(u16)]`: a variant's discriminant is its opcode",
        ))
    }
}

fn parse_variant(variant: &syn::Variant) -> syn::Result<Variant<'_>> {
    let not_supported = || {
        syn::Error::new_spanned(
            variant,
            "a CmdSet variant must wrap exactly one `#[derive(Command)]` struct, as `Name(Args)`",
        )
    };
    let syn::Fields::Unnamed(fields) = &variant.fields else {
        return Err(not_supported());
    };
    let mut unnamed = fields.unnamed.iter();
    let field = unnamed.next().ok_or_else(not_supported)?;
    if unnamed.next().is_some() {
        return Err(not_supported());
    }
    let (_, opcode) = variant.discriminant.as_ref().ok_or_else(|| {
        syn::Error::new_spanned(
            &variant.ident,
            "give this command an opcode, its discriminant: `Name(Args) = 1`",
        )
    })?;
    Ok(Variant {
        name: &variant.ident,
        ty: &field.ty,
        opcode,
    })
}
